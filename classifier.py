# Pipeline Construction
# ─────────────────────────────────────────────────────────────────────────────

def build_pipelines() -> dict:
    """
    Return a dictionary of named scikit-learn Pipelines.

    Each pipeline bundles:
      Step 1 — TfidfVectorizer  (text → numeric feature matrix)
      Step 2 — Classifier       (numeric features → label prediction)

    TF-IDF settings
    ---------------
    - ngram_range=(1, 2)  : unigrams + bigrams capture short phrases
    - max_features=50,000 : caps vocabulary for memory efficiency
    - sublinear_tf=True   : apply 1 + log(tf) scaling to reduce outlier impact
    - min_df=2            : ignore tokens appearing in < 2 documents
    - stop_words="english" : remove common English stopwords
    """
    shared_tfidf = dict(
        ngram_range=(1, 2),
        max_features=MAX_FEATURES,
        sublinear_tf=True,
        min_df=2,
        stop_words="english",
    )

    pipelines = {
        "Naive Bayes": Pipeline([
            ("tfidf", TfidfVectorizer(**shared_tfidf)),
            ("clf",   MultinomialNB(alpha=0.1)),
        ]),
        "Logistic Regression": Pipeline([
            ("tfidf", TfidfVectorizer(**shared_tfidf)),
            ("clf",   LogisticRegression(
                C=5.0, max_iter=1000, solver="lbfgs",
                random_state=RANDOM_STATE, n_jobs=-1
            )),
        ]),
        "Linear SVM": Pipeline([
            ("tfidf", TfidfVectorizer(**shared_tfidf)),
            ("clf",   LinearSVC(C=1.0, max_iter=2000, random_state=RANDOM_STATE)),
        ]),
    }
    return pipelines


# ─────────────────────────────────────────────────────────────────────────────
# Training & Evaluation
# ─────────────────────────────────────────────────────────────────────────────

def train_and_evaluate(pipelines: dict, X_train, X_test, y_train, y_test) -> dict:
    """
    Train every pipeline and collect evaluation metrics.

    Returns
    -------
    results : dict  {model_name: {accuracy, f1, report, confusion_matrix, pipeline}}
    """
    banner("3. Training & Evaluating Models")
    results = {}

    for name, pipe in pipelines.items():
        print(f"\n  ▶  {name}")
        t0 = time.time()

        # ── Train ────────────────────────────────────────────────────────────
        pipe.fit(X_train, y_train)
        train_time = time.time() - t0

        # ── Predict ──────────────────────────────────────────────────────────
        y_pred = pipe.predict(X_test)

        # ── Metrics ──────────────────────────────────────────────────────────
        acc  = accuracy_score(y_test, y_pred)
        f1   = f1_score(y_test, y_pred, average="weighted")
        cm   = confusion_matrix(y_test, y_pred)
        rep  = classification_report(y_test, y_pred,
                                     target_names=["Negative", "Positive"])

        print(f"     Accuracy  : {acc:.4f}  ({acc*100:.2f}%)")
        print(f"     F1-Score  : {f1:.4f}")
        print(f"     Train time: {train_time:.2f}s")
        print(f"\n{rep}")

        results[name] = {
            "accuracy": acc,
            "f1": f1,
            "report": rep,
            "confusion_matrix": cm,
            "pipeline": pipe,
            "train_time": train_time,
        }

    return results


def cross_validate(pipelines: dict, X_train, y_train, cv: int = 5) -> dict:
    """
    Run k-fold cross-validation on the training split for robust estimates.

    Returns
    -------
    cv_scores : dict  {model_name: mean_cv_accuracy}
    """
    banner("4. Cross-Validation (5-Fold)")
    cv_scores = {}
    for name, pipe in pipelines.items():
        scores = cross_val_score(pipe, X_train, y_train,
                                 cv=cv, scoring="accuracy", n_jobs=-1)
        cv_scores[name] = scores.mean()
        print(f"  {name:25s}  CV Accuracy: {scores.mean():.4f} ± {scores.std():.4f}")
    return cv_scores


