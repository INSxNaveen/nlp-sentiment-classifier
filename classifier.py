def banner(text: str) -> None:
    """Print a formatted section banner."""
    width = 70
    print("\n" + "═" * width)
    print(f"  {text}")
    print("═" * width)


def ensure_dirs(*dirs: str) -> None:
    """Create directories if they don't already exist."""
    for d in dirs:
        os.makedirs(d, exist_ok=True)


