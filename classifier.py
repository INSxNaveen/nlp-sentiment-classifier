# ─────────────────────────────────────────────────────────────────────────────
# Model Persistence
# ─────────────────────────────────────────────────────────────────────────────

def save_best_model(results: dict) -> str:
    """
    Serialise the highest-accuracy pipeline to disk with pickle.

    Returns
    -------
    best_name : str  Name of the winning model
    """
    best_name = max(results, key=lambda n: results[n]["accuracy"])
    best_pipe = results[best_name]["pipeline"]

    path = os.path.join(MODELS_DIR, "best_model.pkl")
    with open(path, "wb") as f:
        pickle.dump({"model_name": best_name, "pipeline": best_pipe}, f)

    print(f"\n  ✓ Best model ({best_name}) saved → {path}")
    return best_name


def load_best_model() -> tuple:
    """
    Load the serialised best model from disk.

    Returns
    -------
    (model_name, pipeline)
    """
    path = os.path.join(MODELS_DIR, "best_model.pkl")
    if not os.path.exists(path):
        return None, None
    with open(path, "rb") as f:
        obj = pickle.load(f)
    return obj["model_name"], obj["pipeline"]


# ─────────────────────────────────────────────────────────────────────────────
# CLI Prediction
# ─────────────────────────────────────────────────────────────────────────────

def predict_text(text: str) -> None:
    """
    Load the best saved model and predict the sentiment of *text*.
    Prints a human-readable result with confidence (where available).
    """
    model_name, pipe = load_best_model()
    if pipe is None:
        print("  ✗ No trained model found. Run:  python classifier.py --train")
        return

    prediction = pipe.predict([text])[0]
    label      = LABEL_MAP[prediction]

    # Probability estimates (not available for LinearSVC without calibration)
    try:
        proba    = pipe.predict_proba([text])[0]
        conf     = max(proba) * 100
        conf_str = f"  Confidence : {conf:.1f}%"
    except AttributeError:
        conf_str = "  Confidence : N/A (LinearSVC)"

    print("\n" + "─" * 50)
    print(f"  Model      : {model_name}")
    print(f"  Input text : {text[:80]}{'…' if len(text) > 80 else ''}")
    print(f"  Sentiment  : {label}")
    print(conf_str)
    print("─" * 50)


# ─────────────────────────────────────────────────────────────────────────────
# Full Training Pipeline
# ─────────────────────────────────────────────────────────────────────────────

def run_training_pipeline() -> None:
    """End-to-end: load data → preprocess → train → evaluate → visualise → save."""
    ensure_dirs(MODELS_DIR, PLOTS_DIR)

    # 1. Data
    X, y = load_data()

    # 2. Preprocessing
    banner("2. Preprocessing Text")
    X = preprocess_text(X)
    print(f"  ✓ Cleaned {len(X):,} documents")

    # 3. Split
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=TEST_SIZE, random_state=RANDOM_STATE, stratify=y
    )
    print(f"  ✓ Train: {len(X_train):,}  |  Test: {len(X_test):,}")

    # 4. Build pipelines
    pipelines = build_pipelines()

    # 5. Train & evaluate
    results = train_and_evaluate(pipelines, X_train, X_test, y_train, y_test)

    # 6. Cross-validation
    cross_validate(pipelines, X_train, y_train)

    # 7. Visualisations
    banner("5. Generating Visualisations")
    plot_model_comparison(results)
    plot_confusion_matrices(results)
    plot_top_features(results)
    plot_training_time(results)

    # 8. Save best model
    banner("6. Saving Best Model")
    best = save_best_model(results)

    banner("✅ Pipeline Complete")
    print(f"  Best model : {best}  ({results[best]['accuracy']*100:.2f}% accuracy)")
    print(f"  Plots      : ./{PLOTS_DIR}/")
    print(f"  Model      : ./{MODELS_DIR}/best_model.pkl\n")


