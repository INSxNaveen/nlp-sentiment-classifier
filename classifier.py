def parse_args():
    parser = argparse.ArgumentParser(
        description="NLP Sentiment Classifier — IMDb Movie Reviews",
        formatter_class=argparse.RawTextHelpFormatter,
    )
    parser.add_argument(
        "--train", action="store_true",
        help="Train all models and generate evaluation plots.",
    )
    parser.add_argument(
        "--text", type=str, default=None,
        help='Predict sentiment for a custom string.\nExample: --text "This movie was amazing!"',
    )
    return parser.parse_args()


def main():
    args = parse_args()

    if not args.train and args.text is None:
        print(__doc__)
        print("Run with --help for usage details.")
        sys.exit(0)

    if args.train:
        run_training_pipeline()

    if args.text:
        banner("Predicting Sentiment")
        predict_text(args.text)


if __name__ == "__main__":
    main()
