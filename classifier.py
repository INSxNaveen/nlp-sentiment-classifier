PALETTE = ["#4C72B0", "#DD8452", "#55A868"]   # accessible colour cycle

def plot_model_comparison(results: dict) -> None:
    """Bar chart comparing Accuracy and F1-Score across all models."""
    names     = list(results.keys())
    accuracies = [results[n]["accuracy"] for n in names]
    f1_scores  = [results[n]["f1"]       for n in names]

    x     = np.arange(len(names))
    width = 0.35

    fig, ax = plt.subplots(figsize=(9, 5))
    bars1 = ax.bar(x - width/2, accuracies, width, label="Accuracy",  color=PALETTE[0])
    bars2 = ax.bar(x + width/2, f1_scores,  width, label="F1-Score",  color=PALETTE[1])

    # Annotate bars
    for bar in bars1:
        ax.text(bar.get_x() + bar.get_width() / 2, bar.get_height() + 0.003,
                f"{bar.get_height():.3f}", ha="center", va="bottom", fontsize=9)
    for bar in bars2:
        ax.text(bar.get_x() + bar.get_width() / 2, bar.get_height() + 0.003,
                f"{bar.get_height():.3f}", ha="center", va="bottom", fontsize=9)

    ax.set_xlabel("Model", fontsize=12)
    ax.set_ylabel("Score", fontsize=12)
    ax.set_title("Model Comparison — Accuracy & F1-Score", fontsize=14, fontweight="bold")
    ax.set_xticks(x)
    ax.set_xticklabels(names, fontsize=11)
    ax.set_ylim(0.80, 1.00)
    ax.legend(fontsize=11)
    ax.grid(axis="y", linestyle="--", alpha=0.5)
    fig.tight_layout()

    path = os.path.join(PLOTS_DIR, "model_comparison.png")
    plt.savefig(path, dpi=150)
    plt.close()
    print(f"  ✓ Saved → {path}")


def plot_confusion_matrices(results: dict) -> None:
    """Side-by-side heatmaps of confusion matrices for all models."""
    n     = len(results)
    fig, axes = plt.subplots(1, n, figsize=(6 * n, 5))
    if n == 1:
        axes = [axes]

    labels = ["Negative", "Positive"]
    for ax, (name, data) in zip(axes, results.items()):
        cm = data["confusion_matrix"]
        sns.heatmap(cm, annot=True, fmt="d", cmap="Blues",
                    xticklabels=labels, yticklabels=labels, ax=ax,
                    linewidths=0.5, linecolor="white",
                    annot_kws={"size": 13, "weight": "bold"})
        ax.set_title(name, fontsize=13, fontweight="bold")
        ax.set_xlabel("Predicted Label", fontsize=11)
        ax.set_ylabel("True Label",      fontsize=11)

    fig.suptitle("Confusion Matrices — All Models", fontsize=15, fontweight="bold", y=1.02)
    fig.tight_layout()

    path = os.path.join(PLOTS_DIR, "confusion_matrices.png")
    plt.savefig(path, dpi=150, bbox_inches="tight")
    plt.close()
    print(f"  ✓ Saved → {path}")


def plot_top_features(results: dict, n_features: int = 20) -> None:
    """
    Horizontal bar charts of the top TF-IDF features for
    Logistic Regression (coefficients are directly interpretable).
    """
    name = "Logistic Regression"
    if name not in results:
        return

    pipe       = results[name]["pipeline"]
    vectorizer = pipe.named_steps["tfidf"]
    clf        = pipe.named_steps["clf"]

    feature_names = np.array(vectorizer.get_feature_names_out())
    coefs         = clf.coef_[0]

    top_pos_idx = np.argsort(coefs)[-n_features:][::-1]
    top_neg_idx = np.argsort(coefs)[:n_features]

    fig, axes = plt.subplots(1, 2, figsize=(14, 7))

    for ax, idx, title, colour in [
        (axes[0], top_pos_idx, "Top Positive Features", "#2ecc71"),
        (axes[1], top_neg_idx, "Top Negative Features", "#e74c3c"),
    ]:
        ax.barh(feature_names[idx][::-1], coefs[idx][::-1], color=colour, alpha=0.85)
        ax.set_title(title, fontsize=13, fontweight="bold")
        ax.set_xlabel("Coefficient Weight", fontsize=11)
        ax.grid(axis="x", linestyle="--", alpha=0.5)

    fig.suptitle(f"Logistic Regression — Top {n_features} Features by Class",
                 fontsize=14, fontweight="bold")
    fig.tight_layout()

    path = os.path.join(PLOTS_DIR, "top_features.png")
    plt.savefig(path, dpi=150, bbox_inches="tight")
    plt.close()
    print(f"  ✓ Saved → {path}")


