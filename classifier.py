def load_data(csv_path: str = DATA_CSV):
    """
    Load the IMDb sentiment dataset from a CSV file.

    Returns
    -------
    X : list[str]   Raw review texts
    y : np.ndarray  Binary labels (0 = negative, 1 = positive)
    """
    banner("1. Loading Dataset")

    if not os.path.exists(csv_path):
        print(f"  ✗ Dataset not found at '{csv_path}'.")
        print("  → Run  python generate_data.py  first, then retry.")
        sys.exit(1)

    df = pd.read_csv(csv_path)
    df = shuffle(df, random_state=RANDOM_STATE).reset_index(drop=True)

    print(f"  ✓ Loaded {len(df):,} reviews from '{csv_path}'")
    print(f"  ✓ Class distribution:\n{df['label'].value_counts().to_string()}")

    X = df["text"].tolist()
    y = df["label"].values
    return X, y


def preprocess_text(texts: list) -> list:
    """
    Light-touch text cleaning applied *before* TF-IDF vectorisation:

    - Strip leading/trailing whitespace
    - Collapse multiple spaces
    - Convert to lower-case

    Note: heavy cleaning (stopword removal, stemming) is intentionally
    deferred to TfidfVectorizer so the pipeline remains reproducible.
    """
    import re
    cleaned = []
    for t in texts:
        t = t.strip()
        t = re.sub(r"\s+", " ", t)
        t = t.lower()
        cleaned.append(t)
    return cleaned


