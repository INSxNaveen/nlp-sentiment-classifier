RANDOM_STATE  = 42
TEST_SIZE     = 0.20       # 80 / 20 train-test split
MAX_FEATURES  = 50_000     # TF-IDF vocabulary cap
MODELS_DIR    = "models"
PLOTS_DIR     = "plots"
